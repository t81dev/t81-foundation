#!/usr/bin/env python3
"""Action CLI negatives and an explicit, YAML-parsed permission budget.

Requires PyYAML 6.0.3. The fixtures record the reviewed scope budget and
independently verified upstream identities; they are not generated by tests.
"""
import json
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile
import unittest

import yaml

REPO = Path(__file__).resolve().parents[2]
FIXTURES = REPO / 'tests/ci/fixtures/workflow-supply-chain'


def permission_profile(root):
    result = {}
    for path in sorted((root / '.github/workflows').glob('*.y*ml')):
        data = yaml.safe_load(path.read_text())
        result[path.name] = {
            'workflow': data.get('permissions'),
            'jobs': {k: v['permissions'] for k, v in data.get('jobs', {}).items()
                     if 'permissions' in v},
        }
    return result


def enforce_budget(root):
    if permission_profile(root) != json.loads((FIXTURES / 'permissions.json').read_text()):
        raise ValueError('workflow/job token permissions differ from reviewed budget')


class SupplyChainTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        shutil.copytree(REPO / '.github/workflows', self.root / '.github/workflows')

    def audit(self, script, *args):
        return subprocess.run([sys.executable, str(REPO / 'scripts/ci' / script),
                               '--repo-root', str(self.root), *args],
                              capture_output=True, text=True, timeout=10)

    def test_current_actions_and_permissions_pass(self):
        for script, args in [('audit_workflow_actions.py', ['--max-tagged', '0', '--max-unknown', '0']),
                             ('audit_workflow_permissions.py', ['--max-missing', '0'])]:
            result = self.audit(script, *args)
            self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
        enforce_budget(self.root)

    def test_mutable_or_malformed_action_references_fail(self):
        path = self.root / '.github/workflows/probe.yml'
        for ref in ['docker/login-action@v4', 'pypa/gh-action-pypi-publish@release/v1',
                    'actions/checkout@' + 'a' * 39, 'actions/checkout@' + 'a' * 41,
                    'actions/checkout@' + 'g' * 40, 'actions/checkout', 'unclassified']:
            with self.subTest(ref=ref):
                path.write_text('jobs:\n  probe:\n    steps:\n      - uses: ' + ref + '\n')
                result = self.audit('audit_workflow_actions.py', '--max-tagged', '0', '--max-unknown', '0')
                self.assertEqual(result.returncode, 1, result.stdout + result.stderr)

    def test_missing_explicit_permissions_fails_audit(self):
        path = self.root / '.github/workflows/qemu-boot-x86.yml'
        path.write_text(path.read_text().replace('permissions:\n  contents: read\n', ''))
        result = self.audit('audit_workflow_permissions.py', '--max-missing', '0')
        self.assertEqual(result.returncode, 1)
        self.assertIn('qemu-boot-x86.yml', result.stderr)

    def test_expanded_scopes_and_job_overrides_fail_budget(self):
        path = self.root / '.github/workflows/qemu-boot-x86.yml'
        original = path.read_text()
        variants = [
            original.replace('contents: read', 'contents: write'),
            original.replace('contents: read', 'contents: read\n  packages: write'),
            original.replace('permissions:\n  contents: read', 'permissions: write-all'),
            original.replace('    steps:', '    permissions:\n      contents: write\n    steps:', 1),
        ]
        for changed in variants:
            with self.subTest(permissions=changed[:300]):
                path.write_text(changed)
                with self.assertRaisesRegex(ValueError, 'reviewed budget'):
                    enforce_budget(self.root)

    def test_existing_main_discovery_workflow_cannot_expand_permissions(self):
        path = self.root / '.github/workflows/research-commons.yml'
        original = path.read_text()
        self.assertIn('contents: read', original)
        enforce_budget(self.root)
        path.write_text(original.replace('contents: read', 'contents: write', 1))
        with self.assertRaisesRegex(ValueError, 'reviewed budget'):
            enforce_budget(self.root)

    def test_every_new_pin_matches_verified_identity(self):
        workflows = '\n'.join(p.read_text() for p in (self.root / '.github/workflows').glob('*.y*ml'))
        for pin in json.loads((FIXTURES / 'pins.json').read_text()):
            self.assertRegex(pin['sha'], r'^[0-9a-f]{40}$')
            self.assertIn('uses: ' + pin['repository'] + '@' + pin['sha'], workflows)
            # Exactly two sites: corrected production use and manual smoke use.
            self.assertEqual(workflows.count('uses: ' + pin['repository'] + '@' + pin['sha']), 2)

    def test_smoke_has_no_publish_credentials_or_write_scopes(self):
        data = yaml.safe_load((self.root / '.github/workflows/ci.yml').read_text())
        job = data['jobs']['workflow-action-smoke']
        self.assertEqual(job['if'], "github.event_name == 'workflow_dispatch'")
        self.assertNotIn('needs', job)
        self.assertEqual(job['permissions'], {'contents': 'read'})
        for step in job['steps']:
            if step.get('uses', '').startswith('docker/build-push-action@'):
                self.assertIs(step['with']['push'], False)
            if step.get('uses', '').startswith('pypa/gh-action-pypi-publish@'):
                self.assertIs(step['with']['attestations'], False)
                self.assertEqual(step['with']['password'], 'disposable-local-fixture')
                self.assertEqual(step['with']['repository-url'], '${{ steps.endpoints.outputs.pypi }}')


if __name__ == '__main__':
    unittest.main(verbosity=2)
