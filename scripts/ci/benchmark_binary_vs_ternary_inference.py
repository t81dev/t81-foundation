#!/usr/bin/env python3
"""Benchmark gguf (binary) vs t3k (ternary) inference/benchmark lanes.

This script is reproducibility-focused:
- Runs repeated `t81_ai benchmark run` probes for `gguf` and `t3k`.
- Runs one `t81_ai inference run` probe for each lane.
- Emits JSON + Markdown summaries with deltas.

If a real t3k model is not provided, a deterministic surrogate artifact can be
generated by copying the source gguf and recording provenance metadata.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import shutil
import statistics
import subprocess
import sys
from datetime import UTC, datetime
from pathlib import Path
from typing import Any


SCHEMA_VERSION = "t81.ai.binary-vs-ternary-benchmark.v1"


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        while True:
            chunk = f.read(1024 * 1024)
            if not chunk:
                break
            h.update(chunk)
    return h.hexdigest()


def parse_json(path: Path) -> dict[str, Any]:
    return json.loads(path.read_text(encoding="utf-8"))


def run_cmd(cmd: list[str]) -> tuple[int, str, str]:
    p = subprocess.run(cmd, capture_output=True, text=True, check=False)
    return p.returncode, p.stdout, p.stderr


def mean(values: list[float]) -> float:
    return statistics.fmean(values) if values else 0.0


def stdev(values: list[float]) -> float:
    return statistics.pstdev(values) if len(values) > 1 else 0.0


def parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser(description="Benchmark binary (gguf) vs ternary (t3k) lanes.")
    p.add_argument("--ai-bin", required=True, help="Path to t81_ai binary")
    p.add_argument("--gguf-model", required=True, help="Path to source gguf model")
    p.add_argument("--out-dir", required=True, help="Output directory")
    p.add_argument("--runs", type=int, default=15, help="Benchmark runs per format (default: 15)")
    p.add_argument("--model-id", default="compare-model", help="Model id label")
    p.add_argument(
        "--mode",
        default="reproducible_nondeterministic",
        help="Determinism mode for supported runtime comparison lanes",
    )
    p.add_argument("--prompt", default="binary vs ternary comparison", help="Inference prompt")
    p.add_argument(
        "--t3k-model",
        default="",
        help="Optional path to prebuilt t3k model artifact; if omitted, surrogate policy applies",
    )
    p.add_argument(
        "--surrogate-t3k-policy",
        choices=("auto", "never", "always"),
        default="auto",
        help="How to handle missing t3k model: auto=create surrogate, never=fail, always=force surrogate",
    )
    return p.parse_args()


def ensure_t3k_model(args: argparse.Namespace, out_dir: Path) -> tuple[Path, dict[str, Any]]:
    gguf_model = Path(args.gguf_model).resolve()
    requested_t3k = Path(args.t3k_model).resolve() if args.t3k_model else None

    if args.surrogate_t3k_policy != "always" and requested_t3k and requested_t3k.exists():
        return requested_t3k, {
            "method": "provided",
            "path": str(requested_t3k),
            "sha256": sha256_file(requested_t3k),
        }

    if args.surrogate_t3k_policy == "never":
        raise SystemExit("t3k model is required when --surrogate-t3k-policy=never")

    models_dir = out_dir / "models"
    models_dir.mkdir(parents=True, exist_ok=True)
    surrogate = models_dir / f"{gguf_model.stem}.t3k.surrogate.gguf"
    shutil.copy2(gguf_model, surrogate)
    return surrogate, {
        "method": "surrogate_copy",
        "path": str(surrogate),
        "sha256": sha256_file(surrogate),
        "source_path": str(gguf_model),
        "source_sha256": sha256_file(gguf_model),
        "note": "Surrogate uses byte-identical gguf payload; use a real converted t3k artifact for true format-level performance claims.",
    }


def run_benchmark_matrix(
    ai_bin: Path,
    model_id: str,
    mode: str,
    gguf_model: Path,
    t3k_model: Path,
    runs: int,
    out_dir: Path,
) -> tuple[dict[str, Any], list[str]]:
    errors: list[str] = []
    matrix: dict[str, Any] = {}

    lane_to_model = {
        "gguf": gguf_model,
        "t3k": t3k_model,
    }
    for lane, model_path in lane_to_model.items():
        lane_dir = out_dir / lane
        lane_dir.mkdir(parents=True, exist_ok=True)
        results: list[dict[str, Any]] = []
        for i in range(1, runs + 1):
            out_json = lane_dir / f"benchmark_run_{i}.json"
            cmd = [
                str(ai_bin),
                "benchmark",
                "run",
                "--model",
                model_id,
                "--model-file",
                str(model_path),
                "--format",
                lane,
                "--mode",
                mode,
                "--out",
                str(out_json),
            ]
            rc, _stdout, stderr = run_cmd(cmd)
            if rc != 0 or not out_json.exists():
                errors.append(
                    f"{lane}: benchmark run {i} failed (rc={rc})"
                    + (f": {stderr.strip().splitlines()[-1]}" if stderr.strip() else "")
                )
                continue
            payload = parse_json(out_json)
            results.append(payload)

        latencies = [float(p.get("latency_ms", 0.0)) for p in results]
        throughputs = [float(p.get("throughput_tokens_per_sec", 0.0)) for p in results]
        det_scores = [float(p.get("determinism_score", 0.0)) for p in results]
        matrix[lane] = {
            "format": lane,
            "model_file": str(model_path),
            "model_file_sha256": sha256_file(model_path),
            "runs_requested": runs,
            "runs_completed": len(results),
            "selected_backends": sorted({str(p.get("selected_backend", "")) for p in results if p.get("selected_backend")}),
            "latency_ms": {
                "avg": mean(latencies),
                "min": min(latencies) if latencies else 0.0,
                "max": max(latencies) if latencies else 0.0,
                "stdev": stdev(latencies),
            },
            "throughput_tokens_per_sec": {
                "avg": mean(throughputs),
                "min": min(throughputs) if throughputs else 0.0,
                "max": max(throughputs) if throughputs else 0.0,
                "stdev": stdev(throughputs),
            },
            "determinism_score": {
                "avg": mean(det_scores),
                "min": min(det_scores) if det_scores else 0.0,
                "max": max(det_scores) if det_scores else 0.0,
            },
        }
    return matrix, errors


def run_inference_probes(
    ai_bin: Path,
    model_id: str,
    mode: str,
    prompt: str,
    gguf_model: Path,
    t3k_model: Path,
    out_dir: Path,
) -> tuple[dict[str, Any], list[str]]:
    errors: list[str] = []
    probes: dict[str, Any] = {}
    out_dir.mkdir(parents=True, exist_ok=True)
    lane_to_model = {
        "gguf": gguf_model,
        "t3k": t3k_model,
    }
    for lane, model_path in lane_to_model.items():
        out_json = out_dir / f"{lane}_inference.json"
        cmd = [
            str(ai_bin),
            "inference",
            "run",
            "--model",
            model_id,
            "--model-file",
            str(model_path),
            "--format",
            lane,
            "--mode",
            mode,
            "--prompt",
            prompt,
            "--out",
            str(out_json),
        ]
        rc, _stdout, stderr = run_cmd(cmd)
        if rc != 0 or not out_json.exists():
            errors.append(
                f"{lane}: inference probe failed (rc={rc})"
                + (f": {stderr.strip().splitlines()[-1]}" if stderr.strip() else "")
            )
            continue
        payload = parse_json(out_json)
        output = str(payload.get("output", ""))
        probes[lane] = {
            "artifact": str(out_json),
            "selected_backend": str(payload.get("selected_backend", "")),
            "generated_tokens": int(payload.get("generated_tokens", 0)),
            "output_sha256": hashlib.sha256(output.encode("utf-8")).hexdigest(),
        }
    return probes, errors


def percent_delta(new: float, baseline: float) -> float:
    if baseline == 0:
        return 0.0
    return (new - baseline) / baseline * 100.0


def main() -> int:
    args = parse_args()
    ai_bin = Path(args.ai_bin).resolve()
    gguf_model = Path(args.gguf_model).resolve()
    out_dir = Path(args.out_dir).resolve()
    out_dir.mkdir(parents=True, exist_ok=True)

    if not ai_bin.exists():
        raise SystemExit(f"ai binary not found: {ai_bin}")
    if not gguf_model.exists():
        raise SystemExit(f"gguf model not found: {gguf_model}")
    if args.runs <= 0:
        raise SystemExit("--runs must be > 0")

    t3k_model, t3k_recipe = ensure_t3k_model(args, out_dir)

    benchmark_matrix, benchmark_errors = run_benchmark_matrix(
        ai_bin=ai_bin,
        model_id=args.model_id,
        mode=args.mode,
        gguf_model=gguf_model,
        t3k_model=t3k_model,
        runs=args.runs,
        out_dir=out_dir / "benchmark_runs",
    )
    inference_probes, inference_errors = run_inference_probes(
        ai_bin=ai_bin,
        model_id=args.model_id,
        mode=args.mode,
        prompt=args.prompt,
        gguf_model=gguf_model,
        t3k_model=t3k_model,
        out_dir=out_dir / "inference_probes",
    )

    errors = benchmark_errors + inference_errors
    gguf = benchmark_matrix.get("gguf", {})
    t3k = benchmark_matrix.get("t3k", {})
    gguf_latency = float(gguf.get("latency_ms", {}).get("avg", 0.0))
    t3k_latency = float(t3k.get("latency_ms", {}).get("avg", 0.0))
    gguf_tp = float(gguf.get("throughput_tokens_per_sec", {}).get("avg", 0.0))
    t3k_tp = float(t3k.get("throughput_tokens_per_sec", {}).get("avg", 0.0))

    comparison = {
        "delta_latency_ms_avg": t3k_latency - gguf_latency,
        "delta_throughput_tokens_per_sec_avg": t3k_tp - gguf_tp,
        "percent_latency_delta": percent_delta(t3k_latency, gguf_latency),
        "percent_throughput_delta": percent_delta(t3k_tp, gguf_tp),
    }

    status = "pass" if not errors else "fail"
    payload = {
        "schema": SCHEMA_VERSION,
        "status": status,
        "generated_at_utc": datetime.now(UTC).isoformat(),
        "ai_bin": str(ai_bin),
        "mode": args.mode,
        "model_id": args.model_id,
        "runs": args.runs,
        "prompt_sha256": hashlib.sha256(args.prompt.encode("utf-8")).hexdigest(),
        "gguf_model": {
            "path": str(gguf_model),
            "sha256": sha256_file(gguf_model),
        },
        "t3k_model": t3k_recipe,
        "benchmark_matrix": benchmark_matrix,
        "inference_probes": inference_probes,
        "comparison": comparison,
        "errors": errors,
    }

    json_path = out_dir / "binary_vs_ternary_benchmark.json"
    md_path = out_dir / "binary_vs_ternary_benchmark.md"
    json_path.write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n", encoding="utf-8")

    lines = [
        "# Binary vs Ternary Benchmark",
        "",
        f"- schema: `{SCHEMA_VERSION}`",
        f"- status: `{status}`",
        f"- ai_bin: `{ai_bin}`",
        f"- runs: `{args.runs}`",
        f"- mode: `{args.mode}`",
        f"- gguf_model_sha256: `{payload['gguf_model']['sha256']}`",
        f"- t3k_method: `{t3k_recipe.get('method', '')}`",
        "",
        "| Lane | Runs | Latency Avg (ms) | Throughput Avg (tok/s) | Backend(s) |",
        "| :--- | ---: | ---: | ---: | :--- |",
    ]
    for lane in ("gguf", "t3k"):
        row = benchmark_matrix.get(lane, {})
        lines.append(
            f"| `{lane}` | `{row.get('runs_completed', 0)}` | "
            f"`{row.get('latency_ms', {}).get('avg', 0.0):.6f}` | "
            f"`{row.get('throughput_tokens_per_sec', {}).get('avg', 0.0):.6f}` | "
            f"`{', '.join(row.get('selected_backends', [])) or '-'}` |"
        )
    lines.extend(
        [
            "",
            f"- delta_latency_ms_avg (t3k-gguf): `{comparison['delta_latency_ms_avg']:.6f}`",
            f"- delta_throughput_avg (t3k-gguf): `{comparison['delta_throughput_tokens_per_sec_avg']:.6f}`",
            f"- percent_latency_delta: `{comparison['percent_latency_delta']:.6f}`",
            f"- percent_throughput_delta: `{comparison['percent_throughput_delta']:.6f}`",
        ]
    )
    if t3k_recipe.get("note"):
        lines.extend(["", f"> NOTE: {t3k_recipe['note']}"])
    md_path.write_text("\n".join(lines) + "\n", encoding="utf-8")

    for err in errors:
        print(f"error: {err}", file=sys.stderr)
    print(f"binary vs ternary benchmark status: {status}")
    print(f"artifact: {json_path}")
    print(f"summary:  {md_path}")
    return 0 if status == "pass" else 1


if __name__ == "__main__":
    sys.exit(main())
